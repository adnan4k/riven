// Package openapi builds an OpenAPI 3.1 document from the manifest using only
// static data: routes, parameters, FormRequest rules, Resources, middleware.
// Nothing is invented; unknown parts are left out or marked with x-riven-*.
package openapi

import (
	"fmt"
	"maps"
	"net/http"
	"regexp"
	"slices"
	"strings"

	"github.com/faysal/riven/engine/manifest"
	"github.com/faysal/riven/engine/rules"
)

// Doc is the OpenAPI document as a generic map, so it serialises exactly
// (including x- extensions) without a large typed model.
type Doc = map[string]any

type Options struct {
	Title   string // default: app name from the manifest
	Version string // info.version, the API's version; default "1.0.0"
}

var paramRe = regexp.MustCompile(`\{(\w+)(\?)?\}`)

// Build returns the OpenAPI document for every route in the manifest.
func Build(m *manifest.Manifest, opts Options) Doc {
	b := builder{schemas: Doc{}, usedIDs: map[string]bool{}, shortNames: map[string]string{}}

	title := opts.Title
	if title == "" && m.App.Name != nil {
		title = *m.App.Name
	}
	if title == "" {
		title = "API"
	}
	version := opts.Version
	if version == "" {
		version = "1.0.0"
	}

	paths := Doc{}
	for _, r := range m.Routes {
		for _, path := range expandOptional(r.URI) {
			item, _ := paths[path].(Doc)
			if item == nil {
				item = Doc{}
				paths[path] = item
			}
			if r.Domain != nil {
				item["servers"] = []Doc{domainServer(*r.Domain, m.App.URL)}
			}
			for _, method := range r.Methods {
				if method == http.MethodHead {
					continue // implied by GET in OpenAPI
				}
				item[strings.ToLower(method)] = b.operation(r, method, path)
			}
		}
	}

	doc := Doc{
		"openapi": "3.1.0",
		"info": Doc{
			"title":       title,
			"version":     version,
			"description": fmt.Sprintf("Generated by riven-engine from a Laravel %s manifest (%s).", m.App.LaravelVersion, m.GeneratedAt.Format("2006-01-02")),
		},
		"paths": paths,
	}
	if m.App.URL != nil {
		doc["servers"] = []Doc{{"url": *m.App.URL}}
	}

	components := Doc{}
	if len(b.schemas) > 0 {
		components["schemas"] = b.schemas
	}
	if b.bearer {
		components["securitySchemes"] = Doc{"bearerAuth": Doc{"type": "http", "scheme": "bearer"}}
	}
	if len(components) > 0 {
		doc["components"] = components
	}
	return doc
}

type builder struct {
	schemas    Doc
	usedIDs    map[string]bool
	shortNames map[string]string // resource class => component name
	bearer     bool
}

func (b *builder) operation(r manifest.Route, method, path string) Doc {
	op := Doc{
		"operationId": b.operationID(r, method),
		"tags":        []string{tag(r.URI)},
		"responses":   b.responses(r, method),
	}
	if r.Action.Type != manifest.ActionClosure && r.Action.Class != nil {
		op["x-riven-action"] = *r.Action.Class + "@" + *r.Action.Method
	}

	params := pathParams(r, path)
	body, query := requestParts(r, method)
	params = append(params, query...)
	if len(params) > 0 {
		op["parameters"] = params
	}
	if body != nil {
		op["requestBody"] = body
	}
	if r.RequiresAuth() {
		b.bearer = true
		op["security"] = []Doc{{"bearerAuth": []string{}}}
	}
	return op
}

// operationID prefers the route name ("users.update"); methods sharing a route
// (PUT|PATCH) and expanded optional paths get a suffix to stay unique.
func (b *builder) operationID(r manifest.Route, method string) string {
	base := ""
	if r.Name != nil {
		base = *r.Name
	} else {
		base = strings.ToLower(method) + "_" + strings.Trim(regexp.MustCompile(`[^A-Za-z0-9]+`).ReplaceAllString(r.URI, "_"), "_")
		base = strings.TrimSuffix(base, "_")
	}

	id := base
	if b.usedIDs[id] {
		id = base + "." + strings.ToLower(method)
	}
	for n := 2; b.usedIDs[id]; n++ {
		id = fmt.Sprintf("%s.%s.%d", base, strings.ToLower(method), n)
	}
	b.usedIDs[id] = true
	return id
}

// tag groups operations by the first path segment after an "api" prefix.
func tag(uri string) string {
	for _, seg := range strings.Split(uri, "/") {
		if seg != "" && seg != "api" && !strings.HasPrefix(seg, "{") && !regexp.MustCompile(`^v\d+$`).MatchString(seg) {
			return seg
		}
	}
	return "default"
}

// expandOptional turns "posts/{slug?}" into ["/posts", "/posts/{slug}"]:
// OpenAPI path parameters are always required.
func expandOptional(uri string) []string {
	segments := strings.Split(strings.Trim(uri, "/"), "/")
	var paths []string
	for i, seg := range segments {
		if strings.HasSuffix(seg, "?}") {
			paths = append(paths, "/"+strings.Join(stripOptional(segments[:i]), "/"))
		}
	}
	paths = append(paths, "/"+strings.Join(stripOptional(segments), "/"))
	return slices.Compact(paths)
}

func stripOptional(segs []string) []string {
	out := make([]string, len(segs))
	for i, s := range segs {
		out[i] = strings.Replace(s, "?}", "}", 1)
	}
	return out
}

func pathParams(r manifest.Route, path string) []Doc {
	patterns := map[string]*string{}
	for _, p := range r.Parameters {
		patterns[p.Name] = p.Pattern
	}

	var out []Doc
	for _, m := range paramRe.FindAllStringSubmatch(path, -1) {
		schema := Doc{"type": "string"}
		if p := patterns[m[1]]; p != nil {
			schema["pattern"] = "^(?:" + *p + ")$"
		}
		out = append(out, Doc{"name": m[1], "in": "path", "required": true, "schema": schema})
	}
	return out
}

// domainServer describes a domain route ("{account}.app.test") as a server
// with variables, keeping the app URL's scheme and port.
func domainServer(domain string, appURL *string) Doc {
	scheme, port := "http", ""
	if appURL != nil {
		if s, rest, ok := strings.Cut(*appURL, "://"); ok {
			scheme = s
			host, _, _ := strings.Cut(rest, "/")
			if i := strings.LastIndexByte(host, ':'); i >= 0 {
				port = host[i:]
			}
		}
	}

	vars := Doc{}
	for _, m := range paramRe.FindAllStringSubmatch(domain, -1) {
		vars[m[1]] = Doc{"default": m[1]}
	}
	srv := Doc{"url": scheme + "://" + strings.ReplaceAll(domain, "?}", "}") + port}
	if len(vars) > 0 {
		srv["variables"] = vars
	}
	return srv
}

// requestParts turns FormRequest rules into a JSON/multipart body, or into
// query parameters for GET/DELETE (Laravel validates the query string there).
func requestParts(r manifest.Route, method string) (body Doc, query []Doc) {
	fr := r.Request.FormRequest
	if fr == nil {
		return nil, nil
	}
	inQuery := method == http.MethodGet || method == http.MethodDelete

	if r.Request.Rules == nil {
		if inQuery {
			return nil, nil
		}
		return Doc{
			"description":           "Validated by " + *fr + ". Its rules need a live request, so the fields aren't known statically.",
			"content":               Doc{"application/json": Doc{"schema": Doc{"type": "object"}}},
			"x-riven-rules-unknown": true,
		}, nil
	}

	res := rules.ToSchema(r.Request.Rules)
	if inQuery {
		props, _ := res.Schema["properties"].(rules.Schema)
		required, _ := res.Schema["required"].([]string)
		for _, name := range slices.Sorted(maps.Keys(props)) {
			query = append(query, Doc{
				"name":     name,
				"in":       "query",
				"required": slices.Contains(required, name),
				"schema":   props[name],
			})
		}
		return nil, query
	}

	contentType := "application/json"
	if res.Multipart {
		contentType = "multipart/form-data"
	}
	body = Doc{
		"description": "Validated by " + *fr + ".",
		"required":    len(r.Request.Rules) > 0,
		"content":     Doc{contentType: Doc{"schema": res.Schema}},
	}
	if len(res.Unmapped) > 0 {
		body["x-riven-unmapped-rules"] = res.Unmapped
	}
	return body, nil
}

func (b *builder) responses(r manifest.Route, method string) Doc {
	resp := Doc{}

	ok := Doc{"description": "Successful response"}
	code := "200"
	if res := r.Response.Resource; res != nil {
		ref := Doc{"$ref": "#/components/schemas/" + b.resourceSchema(*res)}
		var data any = ref
		if r.Response.Collection != nil && *r.Response.Collection {
			data = Doc{"type": "array", "items": ref}
		}
		ok["content"] = Doc{"application/json": Doc{"schema": Doc{
			"type":       "object",
			"properties": Doc{"data": data},
			"required":   []string{"data"},
		}}}
		// Laravel answers 201 when a resource wraps a model created in this request.
		if method == http.MethodPost {
			code = "201"
		}
	}
	resp[code] = ok

	if r.RequiresAuth() {
		resp["401"] = Doc{"description": "Unauthenticated", "content": jsonMessage()}
	}
	if r.Request.FormRequest != nil {
		resp["422"] = Doc{"description": "Validation failed", "content": Doc{"application/json": Doc{"schema": Doc{
			"type": "object",
			"properties": Doc{
				"message": Doc{"type": "string"},
				"errors": Doc{
					"type":                 "object",
					"additionalProperties": Doc{"type": "array", "items": Doc{"type": "string"}},
				},
			},
			"required": []string{"message", "errors"},
		}}}}
	}
	return resp
}

// resourceSchema registers an API Resource under its short class name.
// Its fields aren't analyzed yet (deferred), so it's an open object.
func (b *builder) resourceSchema(class string) string {
	if name, ok := b.shortNames[class]; ok {
		return name
	}
	name := class[strings.LastIndexByte(class, '\\')+1:]
	for taken := true; taken; {
		taken = false
		for _, n := range b.shortNames {
			if n == name {
				taken = true
				name = strings.ReplaceAll(class, `\`, ".")
				break
			}
		}
	}
	b.shortNames[class] = name
	b.schemas[name] = Doc{
		"type":          "object",
		"description":   class + " (fields not analyzed yet).",
		"x-riven-class": class,
	}
	return name
}

func jsonMessage() Doc {
	return Doc{"application/json": Doc{"schema": Doc{
		"type": "object", "properties": Doc{"message": Doc{"type": "string"}}, "required": []string{"message"},
	}}}
}
